/**
 * 화면에 쓸 이름.
 *
 * 1. 명시 매핑에 있으면 그걸 쓴다
 * 2. 없고 이름이 길면, 마지막 어절이 알려진 별명일 때만 떼어낸다
 * 3. 그래도 안 되면 원본 그대로 (자르지 않는다 — 잘린 팀명은 오히려 오해를 부른다)
 */
export const displayTeam = (name: string): string => {
  if (!name) return ''
  const raw = name.trim()
  if (SHORT[raw]) return SHORT[raw]

  // 공백만 다른 표기 흡수 ("KIA타이거즈" 같은 경우)
  const squeezed = raw.replace(/\s+/g, '')
  for (const [k, v] of Object.entries(SHORT)) {
    if (k.replace(/\s+/g, '') === squeezed) return v
  }

  if (raw.length <= 7) return raw

  const parts = raw.split(/\s+/)
  if (parts.length >= 2 && NICKNAME_TAIL.includes(parts[parts.length - 1])) {
    const dropped = parts.slice(0, -1).join(' ')
    if (dropped.length >= 2) return dropped
  }

  return raw
}

/**
 * 글자 수에 따라 폰트 크기를 줄인다.
 *
 * 축약을 거쳐도 "캔자스시티"(5자) 와 "프랑크푸르트"(6자) 는 여전히 길다.
 * base 를 그대로 쓰면 넘치므로 기준 글자 수를 넘는 만큼 비례해서 줄이고
 * min 아래로는 내려가지 않게 막는다.
 */
export const fitFont = (text: string, base: number, min: number, fitChars: number): number => {
  const len = (text || '').length
  if (len <= fitChars) return base
  return Math.max(min, Math.round((base * fitChars) / len))
}

