/** 대소문자·공백 무시 조회를 위한 정규화 인덱스 (모듈 로드 시 1회) */
const INDEX: Record<string, string> = (() => {
  const merged: Record<string, string> = {
    ...(TEAM_NAME_KR as Record<string, string>),
    ...SUPPLEMENT,
  }
  const idx: Record<string, string> = {}
  for (const [k, v] of Object.entries(merged)) {
    idx[k.toLowerCase().trim()] = v
  }
  return idx
})()

/** 영문 팀명 → 한글. 없으면 원문 그대로 돌려준다. */
export function toKoreanTeamName(name: string | null | undefined): string {
  if (!name) return ''
  return INDEX[String(name).toLowerCase().trim()] ?? name
}

export default toKoreanTeamName
